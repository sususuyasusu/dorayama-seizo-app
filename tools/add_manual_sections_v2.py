def main():
    ws = manual_layer._ws(manual_layer.CONTENT_TAB, manual_layer.CONTENT_HEADER)
    vals = ws.get_all_values()
    existing_bars = {(r[0], r[3]) for r in vals if len(r) > 3 and r[1] == "見出し"}

    def block_exists(rows):
        head = next(r for r in rows if r[1] == "見出し")
        return (head[0], head[3]) in existing_bars

    # カウンターのクレームブロック: 最後のカウンター行の直後に挿入
    if not block_exists(ROWS_CLAIM):
        last = max(i for i, r in enumerate(vals, start=1) if r and r[0] == "カウンター")
        for off, row in enumerate(ROWS_CLAIM):
            ws.insert_row(list(row), index=last + 1 + off, value_input_option="RAW")
        print(f"カウンター: クレーム対応 {len(ROWS_CLAIM)}行を挿入")
    else:
        print("カウンター: 既存のためスキップ")

    # 新カテゴリ2つは末尾に追加
    for rows, name in ((ROWS_SHINJIN, "はじめての人"), (ROWS_SHOHIN, "商品知識")):
        if not block_exists(rows):
            ws.append_rows([list(r) for r in rows], value_input_option="RAW")
            print(f"{name}: {len(rows)}行を追加")
        else:
            print(f"{name}: 既存のためスキップ")

    wu = manual_layer._ws(manual_layer.UPDATES_TAB, manual_layer.UPDATES_HEADER)
    today = date.today().strftime("%Y/%m/%d")
    existing_titles = {r[1] for r in wu.get_all_values() if len(r) > 1}
    n = 0
    for title, note, cat in UPDATES:
        if title not in existing_titles:
            wu.append_row([today, title, note, cat, ""], value_input_option="RAW")
            n += 1
    print(f"お知らせ: {n}件追加")
    data_layer.invalidate()


if __name__ == "__main__":
    main()
